import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const html=fs.readFileSync(new URL("../index.html",import.meta.url),"utf8");
const start=html.indexOf('    /* ---------- Live sync merge state ----------');
const end=html.indexOf('    /* ---------- 4.5.20 live-sync-only transport ----------',start);
assert.ok(start>=0&&end>start,"Live sync merge implementation block can be isolated");
const block=html.slice(start,end);
const source=`(function(){const normTxt=v=>String(v||"").trim().toLowerCase().replace(/\\s+/g," ");${block};return {mergePracticeState,mergeReadingItem,mergeLocalProgressValue,progressPracticeKey,normalizePracticeStateDates};})()`;
const api=vm.runInNewContext(source,{Date,JSON,Set,Map,Math,Number,String,Object,Array,Error,console});
let local={progressive_level:4,streak:5,times_seen:10,times_correct:8,times_wrong:2,last_seen:"2026-09-08T10:00:00.000Z"};
let incoming={progressive_level:3,streak:2,times_seen:11,times_correct:8,times_wrong:3,last_seen:"2026-09-08T11:00:00.000Z"};
let merged=api.mergePracticeState(local,incoming).row;
assert.equal(merged.progressive_level,3,"newer live lapse can lower Adaptive level");
assert.equal(merged.streak,2,"newer scheduling state wins");
assert.equal(merged.times_seen,11,"cumulative counters never regress");
local={progressive_level:3,streak:2,times_seen:11,last_seen:"2026-09-08T11:00:00.000Z"};
incoming={progressive_level:5,streak:6,times_seen:8,last_seen:"2026-09-08T09:00:00.000Z"};
merged=api.mergePracticeState(local,incoming).row;
assert.equal(merged.progressive_level,3,"older peer state cannot overwrite a newer local answer");
const shared=api.mergeReadingItem({key:"de|x",lastSeen:100,evidence:{words:{seen:4,correct:3,wrong:1,lastAt:100}},storyState:{lvl:2,explicitUnknownAt:80,readingMisses:1}},{key:"de|x",lastSeen:120,evidence:{words:{seen:3,correct:3,wrong:2,lastAt:120}},storyState:{lvl:1,explicitUnknownAt:120,readingMisses:2}});
assert.equal(shared.evidence.words.seen,4);assert.equal(shared.evidence.words.wrong,2);assert.equal(shared.storyState.explicitUnknownAt,120);assert.equal(shared.storyState.readingMisses,2);
const older=JSON.stringify({position:12,blockClock:9}),newer=JSON.stringify({position:18,blockClock:11});assert.equal(api.mergeLocalProgressValue(older,newer),newer);
const numeric=api.normalizePracticeStateDates({last_seen:1725793200000});assert.equal(typeof numeric.last_seen,"string","old numeric practice dates normalize before merge");
console.log("Live sync merge semantics passed.");
